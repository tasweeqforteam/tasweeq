#!/usr/bin/env bash
# design-director self-test: loadability, tool unit checks, regression fixture, cases A–F.
# Usage: bash .claude/skills/design-director/scripts/selftest.sh [--no-cases]
set -u
SKILL="$(cd "$(dirname "$0")/.." && pwd)"
cd "$SKILL"
fail=0
ok()   { printf '  \033[32mPASS\033[0m %s\n' "$1"; }
bad()  { printf '  \033[31mFAIL\033[0m %s\n' "$1"; fail=1; }
warn() { printf '  \033[33mSKIP\033[0m %s\n' "$1"; }

echo "1 · Loadability"
fm=$(awk 'NR==1&&/^---$/{f=1;next} f&&/^---$/{exit} f' SKILL.md)
name=$(printf '%s\n' "$fm" | sed -n 's/^name: *//p')
desc=$(printf '%s\n' "$fm" | sed -n 's/^description: *//p')
[ "$name" = "$(basename "$SKILL")" ] && ok "front matter name = $name" || bad "front matter name '$name' must equal directory name"
[ -n "$desc" ] && [ ${#desc} -le 1024 ] && ok "description present (${#desc} chars)" || bad "description missing or > 1024 chars"
missing=0
for p in $(grep -oE '(modules|scripts|templates|library|tests)/[A-Za-z0-9_./-]+\.(md|py|mjs|sh|css|html|json|jsonl)' SKILL.md modules/*.md | cut -d: -f2 | grep -v '^tests/results/' | sort -u); do
  [ -e "$p" ] || { bad "referenced file missing: $p"; missing=1; }
done
[ $missing -eq 0 ] && ok "every file referenced by SKILL.md and modules exists"

echo "2 · Tool unit checks"
top=$(python3 scripts/grid.py --format story --columns 4 | python3 -c 'import json,sys;print(json.load(sys.stdin)["margins"]["top"])')
[ "$top" -ge 250 ] && ok "grid.py story safe-area snaps up (top margin $top ≥ 250)" || bad "grid.py story top margin $top < 250"
python3 scripts/library.py validate >/dev/null && ok "library.py validate ($(wc -l < library/references.jsonl | tr -d ' ') records)" || bad "library.py validate"
if python3 -c 'import fontTools' 2>/dev/null; then
  python3 scripts/glyph_coverage.py --text "عرض خاص ٢٠٪، Sale – 50%" assets/fonts/alexandria-arabic-wght-normal.woff2 assets/fonts/inter-tight-latin-wght-normal.woff2 >/dev/null \
    && ok "glyph_coverage.py: default stack (Alexandria + Inter Tight) covers mixed sample copy" || bad "glyph_coverage.py default stack"
  python3 scripts/glyph_coverage.py --text "عرض" assets/fonts/inter-tight-latin-wght-normal.woff2 >/dev/null \
    && bad "glyph_coverage.py failed to report missing Arabic in Inter Tight" || ok "glyph_coverage.py reports glyphs no font in the stack covers"
else
  warn "glyph_coverage.py (pip install fonttools)"
fi
node scripts/render.mjs --help >/dev/null && ok "render.mjs loads Playwright" || bad "render.mjs cannot start"

echo "3 · Regression fixture (every planted defect must be detected)"
tmp=$(mktemp -d)
node scripts/qa.mjs tests/fixtures/defects.html --json "$tmp/def.json" >/dev/null 2>&1
if [ -s "$tmp/def.json" ]; then
  miss=$(python3 - "$tmp/def.json" tests/fixtures/defects.expect <<'PY'
import json, sys
got = {i["check"] for i in json.load(open(sys.argv[1]))["issues"]}
exp = open(sys.argv[2]).read().split()
print(" ".join(e for e in exp if e not in got))
PY
)
  n=$(wc -w < tests/fixtures/defects.expect | tr -d ' ')
  [ -z "$miss" ] && ok "qa.mjs detected all $n planted defect classes" || bad "qa.mjs missed: $miss"
else
  bad "qa.mjs produced no report for the fixture"
fi

if [ "${1:-}" != "--no-cases" ]; then
  echo "4 · Cases"
  summary="tests/results/SUMMARY.md"
  {
    echo "# Test results"
    echo
    echo "Generated by \`scripts/selftest.sh\` on $(date -u +%Y-%m-%dT%H:%MZ). Rubric scores and critique are in each case's NOTES.md."
    echo
    echo "| Case | qa.mjs verdict | critical | major | minor | fonts rendered |"
    echo "|---|---|---|---|---|---|"
  } > "$summary"
  for dir in tests/cases/*/; do
    id=$(basename "$dir"); out="tests/results/$id"; mkdir -p "$out"
    node scripts/render.mjs "$dir/index.html" --out "$out/${id%%-*}" --grid >/dev/null 2>&1 || bad "$id render"
    node scripts/qa.mjs "$dir/index.html" --json "$out/qa.json" >/dev/null 2>&1
    row=$(python3 - "$out/qa.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1])); s = d["summary"]
print(f'{d["verdict"]}|{s["critical"]}|{s["major"]}|{s["minor"]}|{", ".join(d["fontsUsed"])}')
PY
)
    verdict=${row%%|*}
    echo "| $id | ${row//|/ | } |" >> "$summary"
    [ "$verdict" = "PASS" ] && ok "$id: $verdict" || bad "$id: $verdict"
  done
  echo "  summary → $summary"
fi
rm -rf "$tmp"
echo
[ $fail -eq 0 ] && echo "ALL CHECKS PASSED" || echo "SOME CHECKS FAILED"
exit $fail
